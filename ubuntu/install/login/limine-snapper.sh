# Limine bootloader, UKI builds, and snapper snapshot boot entries.
#
# This is the Ubuntu-native rewrite of upstream's login/limine-snapper.sh. Upstream
# is built on mkinitcpio, pacman transaction hooks, /usr/share/libalpm, and
# arch-limine ESP paths, none of which exist here. The pieces it maps onto:
#
#   mkinitcpio hook list            -> /etc/initramfs-tools/conf.d + modules
#   limine-mkinitcpio-hook          -> ukify + /etc/kernel/postinst.d hooks below
#   limine-install (entry-tool)     -> copy BOOTX64.EFI + efibootmgr below
#   pacman -S limine-snapper-sync   -> pacstall package, installed in packaging
#   /usr/share/libalpm re-enable    -> nothing: dpkg kernel hooks always run
#
# The first Limine deployment is part of the manual debootstrap step (see
# ubuntu/README.md). This converges an existing install: it keeps whatever the
# bootloader was built with, and owns the config file, UKIs, and snapshot menu.

# Both packages come from pacstall; skip if this isn't a Limine system at all
if ub-cmd-missing limine; then
  echo "Skipping Limine setup (limine not installed)"
  exit 0
fi

# Detect boot mode. UKIs only exist on UEFI, same guard upstream uses.
EFI=""
[[ -d /sys/firmware/efi ]] && EFI=true

# Snapper snapshot boot needs / on btrfs with /.snapshots as its own mounted
# btrfs subvolume (snapper's create-config layout). Without that layout the
# snapshot entries and the limine-snapper-sync service have nothing to work
# with, so they are skipped rather than left to fail. A plain /.snapshots
# directory on / does not qualify: findmnt reports the containing mount's
# target for it, not the path itself.
snapper_layout_ok() {
  [[ $(findmnt -n -o FSTYPE /) = "btrfs" ]] || return 1
  [[ $(findmnt -n -o TARGET "/.snapshots" 2>/dev/null) == "/.snapshots" ]] || return 1
  [[ $(findmnt -n -o FSTYPE "/.snapshots" 2>/dev/null) = "btrfs" ]]
}

# Find an existing limine.conf so we can preserve its kernel cmdline. Without
# this we cannot know what root=/cryptdevice= the system was built to boot with.
limine_config=""
for candidate in \
  /boot/EFI/ubuntu-limine/limine.conf \
  /boot/EFI/BOOT/limine.conf \
  /boot/EFI/limine/limine.conf \
  /boot/limine/limine.conf \
  /boot/limine.conf \
  /limine.conf; do
  if [[ -f $candidate ]]; then
    limine_config="$candidate"
    break
  fi
done

if [[ -z $limine_config ]]; then
  echo "Error: no limine.conf found; deploy Limine first (see ubuntu/README.md)" >&2
  exit 1
fi

CMDLINE=$(grep -m1 "^[[:space:]]*cmdline:" "$limine_config" | sed 's/^[[:space:]]*cmdline:[[:space:]]*//')

# ---------------------------------------------------------------- initramfs --
# Upstream writes /etc/mkinitcpio.conf.d/omarchy_hooks.conf to get plymouth,
# kms, consolefont and friends into the image. initramfs-tools gets there with
# a conf.d drop-in plus an explicit module list.
sudo mkdir -p /etc/initramfs-tools/conf.d
cat <<EOF | sudo tee /etc/initramfs-tools/conf.d/ubuntu-limine.conf >/dev/null
BOOT_UUI=none
COMPRESS=zstd
EOF

# thunderbolt is not built in on Ubuntu kernels; overlay is needed by overlayroot
# to make read-only snapper snapshots writable while booted.
grep -qxF "thunderbolt" /etc/initramfs-tools/modules 2>/dev/null || echo "thunderbolt" | sudo tee -a /etc/initramfs-tools/modules >/dev/null
grep -qxF "overlay" /etc/initramfs-tools/modules 2>/dev/null || echo "overlay" | sudo tee -a /etc/initramfs-tools/modules >/dev/null
grep -qxF "btrfs" /etc/initramfs-tools/modules 2>/dev/null || echo "btrfs" | sudo tee -a /etc/initramfs-tools/modules >/dev/null

# ------------------------------------------------------------------- config --
# Write /etc/default/limine before anything reads it. limine-snapper-sync takes
# /etc/default/limine in preference to /etc/limine-snapper-sync.conf.
sudo cp "$UBUNTU_PATH/default/limine/default.conf" /etc/default/limine
sudo sed -i "s|@@CMDLINE@@|$CMDLINE|g" /etc/default/limine

# Merge kernel cmdline drop-ins (hardware fixes, hibernation) after the base
# config, same as upstream. These are appended verbatim.
if [[ -d /etc/limine-entry-tool.d ]]; then
  for dropin in /etc/limine-entry-tool.d/*.conf; do
    [[ -f $dropin ]] && sudo tee -a /etc/default/limine <"$dropin" >/dev/null
  done
fi

# UKI and fallback entries only make sense under UEFI.
if [[ -z $EFI ]]; then
  sudo sed -i '/^ENABLE_UKI=/d; /^ENABLE_LIMINE_FALLBACK=/d; /^CUSTOM_UKI_NAME=/d' /etc/default/limine
fi

# Remove any pre-existing config from an ESP subdirectory so Limine does not
# find two configs and silently prefer the stale one. Per CONFIG.md the file
# next to the EFI app is searched before /boot, so leaving it in place would
# shadow everything written below.
if [[ $limine_config != "/boot/limine.conf" ]] && [[ -f $limine_config ]]; then
  sudo rm "$limine_config"
fi

# Overwrite wholesale; the entries themselves are regenerated by the helper
# installed below and by limine-snapper-sync for snapshots.
sudo cp "$UBUNTU_PATH/default/limine/limine.conf" /boot/limine.conf

# Stand-in for limine-entry-tool, which is not ported: its automation assumes
# mkinitcpio/dracut and pacman transactions. This owns the OS entry and one
# child entry per UKI, and leaves the Snapshots submenu to limine-snapper-sync.
sudo install -m 755 "$UBUNTU_PATH/default/limine/ubuntu-limine-entries" /usr/local/bin/ubuntu-limine-entries

# ----------------------------------------------------------------- deploy --
# The bootloader itself is deployed by hand (see ubuntu/README.md), but make
# sure the EFI payload is present and registered, and refresh it when the
# limine package has been upgraded.
ESP="/boot"
if [[ -d /sys/firmware/efi ]]; then
  if [[ ! -f $ESP/EFI/BOOT/BOOTX64.EFI ]] || [[ /usr/share/limine/BOOTX64.EFI -nt $ESP/EFI/BOOT/BOOTX64.EFI ]]; then
    echo "Deploying Limine EFI binary to $ESP"
    sudo mkdir -p "$ESP/EFI/BOOT"
    sudo cp /usr/share/limine/BOOTX64.EFI "$ESP/EFI/BOOT/BOOTX64.EFI"
  fi

  # NVRAM entry, if efibootmgr is available and no entry exists yet. Never
  # clobber an existing entry: the hand-built bootloader may already be
  # registered under a different label.
  if ub-cmd-present efibootmgr; then
    if ! efibootmgr | grep -q "Ubuntu Limine"; then
      # findmnt reports subvolumes as /dev/sda2[/@boot]; strip the bracket part.
      esp_source=$(findmnt -n -o SOURCE "$ESP" | sed 's/\[.*\]//')
      esp_disk="/dev/$(lsblk -no PKNAME "$esp_source")"
      esp_part=$(lsblk -no PARTN "$esp_source")

      if [[ -b $esp_disk ]] && [[ -n $esp_part ]]; then
        echo "Registering Limine in UEFI NVRAM"
        sudo efibootmgr --create --disk "$esp_disk" --part "$esp_part" \
          --label "Ubuntu Limine" --loader '\EFI\BOOT\BOOTX64.EFI' --unicode
      fi
    fi
  fi
fi

# --------------------------------------------------------------- UKI hooks --
# Build a UKI per installed kernel into $ESP/EFI/Linux/ubuntu_<version>.efi.
# limine-snapper-sync looks for these by CUSTOM_UKI_NAME, and copies the ones
# matching a snapshot into the history directory when it syncs.
#
# Unsigned by design: install/preflight/guard.sh requires Secure Boot disabled.
if ub-cmd-present ukify; then
  sudo mkdir -p /etc/kernel/postinst.d /etc/initramfs/post-update.d

  cat <<'HOOK' | sudo tee /etc/kernel/postinst.d/zz-ubuntu-ukify >/dev/null
#!/bin/bash
# Build the Ubuntu Limine UKI for the kernel being installed ($2 is the version).
set -e

version="$2"
esp="/boot"
vmlinuz="/boot/vmlinuz-$version"
initrd="/boot/initrd.img-$version"
output="$esp/EFI/Linux/ubuntu_$version.efi"

[[ -f $vmlinuz ]] || exit 0
[[ -f $initrd ]] || exit 0
[[ -f /etc/default/limine ]] || exit 0

# Reuse the cmdline limine-entry-tool/snapper-sync would build, so UKI and
# snapshot entries agree. Every KERNEL_CMDLINE[default]+= line contributes.
cmdline=$(sed -n 's/^KERNEL_CMDLINE\[default\]+="\(.*\)"$/\1/p' /etc/default/limine | paste -sd' ' -)

mkdir -p "$esp/EFI/Linux"
ukify build \
  --linux="$vmlinuz" \
  --initrd="$initrd" \
  --cmdline="$cmdline" \
  --output="$output"

# Publish the new UKI in the boot menu.
if command -v ubuntu-limine-entries >/dev/null; then
  ubuntu-limine-entries
fi
HOOK

  cat <<'HOOK' | sudo tee /etc/initramfs/post-update.d/zz-ubuntu-ukify >/dev/null
#!/bin/bash
# Rebuild the UKI after update-initramfs regenerates the image.
set -e

version="$1"
vmlinuz="/boot/vmlinuz-$version"
initrd="/boot/initrd.img-$version"
output="/boot/EFI/Linux/ubuntu_$version.efi"

[[ -f $vmlinuz ]] || exit 0
[[ -f $initrd ]] || exit 0
[[ -f $output ]] || exit 0
[[ -f /etc/default/limine ]] || exit 0

cmdline=$(sed -n 's/^KERNEL_CMDLINE\[default\]+="\(.*\)"$/\1/p' /etc/default/limine | paste -sd' ' -)

ukify build \
  --linux="$vmlinuz" \
  --initrd="$initrd" \
  --cmdline="$cmdline" \
  --output="$output"
HOOK

  sudo chmod 755 /etc/kernel/postinst.d/zz-ubuntu-ukify /etc/initramfs/post-update.d/zz-ubuntu-ukify

  # Build a UKI now for the running kernel, rather than waiting for the next
  # kernel package install.
  if ub-cmd-present update-initramfs; then
    update_initramfs_needed=false
    running=$(uname -r)
    if [[ ! -f /boot/initrd.img-$running ]]; then
      echo "Generating initramfs for $running"
      sudo update-initramfs -c -k "$running"
      update_initramfs_needed=true
    fi

    if [[ ! -f /boot/EFI/Linux/ubuntu_$running.efi ]] || [[ $update_initramfs_needed == true ]]; then
      echo "Building UKI for $running"
      cmdline=$(sed -n 's/^KERNEL_CMDLINE\[default\]+="\(.*\)"$/\1/p' /etc/default/limine | paste -sd' ' -)
      sudo mkdir -p /boot/EFI/Linux
      ukify build \
        --linux="/boot/vmlinuz-$running" \
        --initrd="/boot/initrd.img-$running" \
        --cmdline="$cmdline" \
        --output="/boot/EFI/Linux/ubuntu_$running.efi"
    fi

    # Every installed kernel should have an entry, not just the running one.
    ubuntu-limine-entries
  fi
fi

# ----------------------------------------------------------------- snapper --
# Snapshot boot only for the root subvolume; /home is user data and rolling it
# back loses work. Same reasoning as upstream. Skipped entirely when the
# subvolume layout does not support snapper, so the rest of this script
# (bootloader config, UKIs, boot entries) still converges flawlessly.
if snapper_layout_ok; then
  if ub-cmd-present snapper; then
    if ! snapper list-configs 2>/dev/null | grep -q "root"; then
      echo "Creating snapper root config"
      sudo snapper -c root create-config /
    fi

    if [[ -f /etc/snapper/configs/root ]]; then
      sudo cp "$UBUNTU_PATH/default/snapper/root" /etc/snapper/configs/root
    fi

    # Full qgroup accounting is a major performance drag on every write.
    sudo btrfs quota disable / 2>/dev/null || true
  fi

  # Sync snapshot entries and keep them in step with future snapshots.
  if ub-cmd-present limine-snapper-sync; then
    echo "Syncing Limine snapshot entries"
    # Limine may not be able to boot yet on a first run (no entries until this
    # point), so a failure here is not fatal: the entries above still stand.
    sudo limine-snapper-sync || echo "Warning: limine-snapper-sync did not run cleanly" >&2
    chrootable_systemctl_enable limine-snapper-sync.service
  fi
else
  echo "Skipping snapper snapshot boot: /.snapshots is not a btrfs subvolume"
fi

# Fail loudly if the boot menu ended up with no OS entry, which is the symptom
# of a UKI path or cmdline mismatch and is otherwise only visible after reboot.
if ! grep -q "^/+" /boot/limine.conf; then
  echo "Error: no boot entries were added to /boot/limine.conf" >&2
  exit 1
fi

echo "Limine: OK"